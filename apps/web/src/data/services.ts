export function getServiceBySlug(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug);
}

export function getServicesByCategory(categorySlug: string): Service[] {
  return services.filter((s) => s.categorySlug === categorySlug);
}

export function getFeaturedServices(): Service[] {
  return services.filter((s) => s.featured);
}

export function getPopularServices(): Service[] {
  return services.filter((s) => s.popular);
}

export function getRelatedServices(service: Service, limit = 3): Service[] {
  return services.filter((s) => s.categorySlug === service.categorySlug && s.slug !== service.slug).slice(0, limit);
}

export function getServicesByConcern(concernSlug: string): Service[] {
  return services.filter((s) => s.concernSlugs.includes(concernSlug));
}
