export function getBlogBySlug(slug: string): Blog | undefined {
  return blogs.find((b) => b.slug === slug);
}

export function getRelatedBlogs(blog: Blog, limit = 3): Blog[] {
  return blogs.filter((b) => b.category === blog.category && b.slug !== blog.slug).slice(0, limit);
}

export function getBlogsByConcern(concernSlug: string): Blog[] {
  return blogs.filter((b) => b.relatedConcernSlugs.includes(concernSlug));
}
